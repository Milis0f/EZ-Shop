#!/usr/bin/env node
/**
 * Builds the country grid the ASCII planet draws from: one character per cell of a 1.5° grid, telling
 * sea, land, or which analysed country. Run once, by hand, when the map data changes:
 *
 *   node scripts/build-world-grid.mjs path/to/countries-110m.json
 *
 * Input: countries-110m.json of world-atlas 2.0.2 (https://github.com/topojson/world-atlas, ISC),
 * itself made from Natural Earth 1:110m (public domain). Output: src/components/planet/world-grid.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const STEP = 1.5;
const COLS = 360 / STEP;
const ROWS = 180 / STEP;

/** The analysed countries, in the order of their grid letter (a, b, c…), with their ISO numeric code. */
const COUNTRIES = [
  ["FR", "250"], ["BE", "056"], ["CH", "756"], ["LU", "442"], ["DE", "276"], ["AT", "040"],
  ["NL", "528"], ["ES", "724"], ["IT", "380"], ["PT", "620"], ["IE", "372"], ["PL", "616"],
  ["SE", "752"], ["DK", "208"], ["GB", "826"], ["US", "840"], ["CA", "124"], ["AU", "036"],
];

/** A point inside each country, used when it is too small for any cell centre (Luxembourg). */
const FALLBACK_POINT = { LU: [6.1, 49.8], BE: [4.6, 50.6], CH: [8.2, 46.8], NL: [5.5, 52.2], DK: [9.3, 56.1], AT: [14.5, 47.6] };

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/build-world-grid.mjs path/to/countries-110m.json");
  process.exit(1);
}
const topology = JSON.parse(readFileSync(source, "utf8"));
const { scale, translate } = topology.transform;

// Quantised, delta-encoded arcs back to longitude and latitude.
const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indexes) {
  const points = [];
  for (const index of indexes) {
    const arc = index >= 0 ? arcs[index] : [...arcs[~index]].reverse();
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

function polygons(geometry) {
  if (geometry.type === "Polygon") return [geometry.arcs.map(ring)];
  if (geometry.type === "MultiPolygon") return geometry.arcs.map((polygon) => polygon.map(ring));
  return [];
}

/** Even-odd rule over every ring of a polygon: holes cut out. */
function inside([x, y], rings) {
  let hit = false;
  for (const points of rings) {
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [xi, yi] = points[i];
      const [xj, yj] = points[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

const letters = new Map(COUNTRIES.map(([code, id], i) => [id, { code, letter: String.fromCharCode(97 + i) }]));
const shapes = topology.objects.countries.geometries.map((geometry) => {
  const parts = polygons(geometry).map((rings) => {
    const all = rings.flat();
    const xs = all.map((p) => p[0]);
    const ys = all.map((p) => p[1]);
    return { rings, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] };
  });
  return { mark: letters.get(geometry.id)?.letter ?? "#", parts };
});

const grid = Array.from({ length: ROWS }, () => Array(COLS).fill("."));
for (let row = 0; row < ROWS; row += 1) {
  const lat = 90 - (row + 0.5) * STEP;
  for (let col = 0; col < COLS; col += 1) {
    const lon = -180 + (col + 0.5) * STEP;
    for (const shape of shapes) {
      const hit = shape.parts.some(({ rings, box }) => lon >= box[0] && lon <= box[2] && lat >= box[1] && lat <= box[3] && inside([lon, lat], rings));
      if (hit) {
        // An analysed country wins over a neighbour drawn first.
        if (grid[row][col] === "." || shape.mark !== "#") grid[row][col] = shape.mark;
        if (shape.mark !== "#") break;
      }
    }
  }
}

for (const [code] of COUNTRIES) {
  const letter = letters.get(COUNTRIES.find(([c]) => c === code)[1]).letter;
  if (grid.some((row) => row.includes(letter))) continue;
  const [lon, lat] = FALLBACK_POINT[code] ?? [];
  if (lon === undefined) throw new Error(`No cell for ${code}`);
  grid[Math.floor((90 - lat) / STEP)][Math.floor((lon + 180) / STEP)] = letter;
}

const out = path.resolve("src/components/planet/world-grid.ts");
writeFileSync(
  out,
  [
    "/* Generated by scripts/build-world-grid.mjs from world-atlas 2.0.2 (ISC), made from Natural Earth (public domain). Do not edit. */",
    "",
    `/** Cell size in degrees. Row 0 starts at 90°N, column 0 at 180°W. */`,
    `export const GRID_STEP = ${STEP};`,
    `export const GRID_COLS = ${COLS};`,
    `export const GRID_ROWS = ${ROWS};`,
    "",
    `/** Grid letter of each analysed country: "." is sea, "#" other land. */`,
    `export const GRID_LETTERS = ${JSON.stringify(Object.fromEntries(COUNTRIES.map(([code], i) => [code, String.fromCharCode(97 + i)])))} as const;`,
    "",
    "export const WORLD_GRID: readonly string[] = [",
    ...grid.map((row) => `  "${row.join("")}",`),
    "];",
    "",
  ].join("\n"),
);
console.log(`Wrote ${out}: ${ROWS} rows of ${COLS} cells.`);
